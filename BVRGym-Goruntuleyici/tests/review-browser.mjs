import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import net from 'node:net';
import {fileURLToPath} from 'node:url';
const args=Object.fromEntries(process.argv.slice(2).reduce((items,value,i,all)=>i%2?items:[...items,[value.slice(2),all[i+1]]],[]));
const {chromium}=createRequire(import.meta.url)(args.playwright);
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const temporary=await fs.mkdtemp(path.join(os.tmpdir(),'bvrgym-review-'));
const watch=path.join(temporary,'watch'),library=path.join(temporary,'flights'),flight=path.join(library,'custom');
await fs.mkdir(watch);await fs.mkdir(flight,{recursive:true});
const header='Time,Longitude,Latitude,Altitude,Roll (deg),Pitch (deg),Yaw (deg)\n';
await fs.writeFile(path.join(flight,'MiG-29 (Blue) [Blue].csv'),header+'0,18,59,5000,0,0,90\n2,18.01,59,5000,0,0,90');
await fs.writeFile(path.join(flight,'F-16 (Wing) [Blue].csv'),header+'0,18,59.01,5000,0,0,90\n20,18.1,59.01,5000,0,0,90');
await fs.writeFile(path.join(flight,'F-16 (Neutral).csv'),'Time,Longitude,Latitude,Altitude\n0,18,59.02,5000\n20,18,59.02,5000');
await fs.writeFile(path.join(flight,'Meteor (M1) [Red].csv'),header+'5,18,59.03,5000,0,0,90\n15,18.1,59.03,5000,0,0,90');
const socket=net.createServer();await new Promise(resolve=>socket.listen(0,'127.0.0.1',resolve));const port=socket.address().port;await new Promise(resolve=>socket.close(resolve));
const child=spawn(args.python,[path.join(root,'viewer.py'),'--recording',watch,'--port',String(port)],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
let browser;
try{
  await new Promise((resolve,reject)=>{const timeout=setTimeout(()=>reject(new Error('Startup timeout')),10000);child.stdout.on('data',data=>{if(String(data).includes('http://')){clearTimeout(timeout);resolve();}});});
  browser=await chromium.launch({headless:true,executablePath:args.browser,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1500,height:950}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:'+port);
  await page.locator('#open-recording').click();
  await page.route('**/api/choose-directory',async route=>{
    await page.request.post('http://127.0.0.1:'+port+'/api/directory',{data:{path:library}});
    await route.fulfill({json:{cancelled:false,path:await fs.realpath(library)}});
  });
  await page.locator('#change-directory').click();
  await page.locator('#recording-library .library-item').filter({hasText:'custom'}).click();
  await page.waitForFunction(async()=>{const {buffer}=await import('/app.js');return buffer.complete&&buffer.packet.objects===4;}).catch(async error=>{console.log(await page.evaluate(async()=>{const {buffer}=await import('/app.js');return {packet:buffer.packet,status:document.querySelector('#status').textContent,message:document.querySelector('#scene-message').textContent};}));throw error;});
  await page.waitForFunction(()=>document.querySelector('#timeline').max==='20'&&!document.querySelector('#timeline').disabled);
  await page.locator('#seek-time').fill('10');await page.locator('#seek-time').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#timeline').value==='10');
  await page.locator('#entity-list .entity').filter({hasText:'MiG-29'}).click();
  await page.waitForFunction(()=>document.querySelector('#entity-state').textContent.includes('Ölçüm bitti'),null,{timeout:3000}).catch(async error=>{console.log({errors,state:await page.evaluate(()=>({selected:document.querySelector('#selected-name').textContent,time:document.querySelector('#timeline').value,max:document.querySelector('#timeline').max,state:document.querySelector('#entity-state').textContent}))});throw error;});
  assert.ok((await page.locator('#record-warning').textContent()).includes('aynı numaralı'));
  assert.ok((await page.locator('#record-warning').textContent()).includes('genel nesne'));
  await page.evaluate(async()=>{
    const {buffer,scene}=await import('/app.js');
    const mig=[...buffer.tracks.values()].find(t=>t.samples[0].model==='MiG-29').samples[0];
    const neutral=[...buffer.tracks.values()].find(t=>t.samples[0].team==='unknown').samples[0];
    const meteor=[...buffer.tracks.values()].find(t=>t.samples[0].model==='Meteor').samples[0];
    if(!scene.models.get(mig.id).label.classList.contains('stale'))throw new Error('Final sample not marked');
    if(scene.models.get(neutral.id).heading.visible)throw new Error('Unknown heading drawn');
    if(scene.models.get(neutral.id).model.userData.bodyMaterial.color.getHex()!==0xaeb6bf)throw new Error('Unknown team appears friendly');
    if(meteor.kind!=='missile'||meteor.visual_model!=='generic')throw new Error('Missile classification');
  });
  await page.locator('#entity-list .entity').filter({hasText:'Neutral'}).click();await page.waitForTimeout(200);
  assert.equal(await page.locator('#heading').textContent(),'—');
  if(args.screenshot)await page.screenshot({path:args.screenshot});
  await page.locator('#view-2d').click();await page.waitForTimeout(150);assert.equal(await page.locator('#scene2d').isVisible(),true);
  assert.deepEqual(errors,[]);console.log(JSON.stringify({passed:true,directorySelection:true,staleAircraft:true,neutralTeam:true,genericModel:true,missingAttitude:true,errors}));
}finally{
  await browser?.close();child.kill();await new Promise(resolve=>child.exitCode!==null?resolve():child.once('exit',resolve));
  const resolved=path.resolve(temporary);if(!resolved.startsWith(path.resolve(os.tmpdir())+path.sep)||!path.basename(resolved).startsWith('bvrgym-review-'))throw new Error('Unsafe cleanup');
  await fs.rm(resolved,{recursive:true,force:true});
}
